"""
backend/app/schemas/planner_schema.py
======================================
Pydantic v2 schemas for DataInvest AI — Phase 2 Planner Agent.
Provides strongly typed data contracts for analysis planning, task specification,
and future Critic Agent compatibility.
"""

from __future__ import annotations

from typing import Any, Literal, Optional
from pydantic import BaseModel, Field
from app.schemas.profile import ProfileResponse


TaskType = Literal[
    "descriptive_statistics",
    "distribution_analysis",
    "missing_value_investigation",
    "duplicate_investigation",
    "numerical_vs_numerical",
    "two_groups_vs_numerical",
    "multiple_groups_vs_numerical",
    "categorical_vs_categorical",
    "outlier_sensitivity",
    "binary_classification",
    "clustering",
    "customer_segmentation",
    "text_classification",
    "fake_news_classification",
]

PriorityLevel = Literal["high", "medium", "low"]


class SelectedColumn(BaseModel):
    """Metadata and selection rationale for an individual column in the plan."""
    column: str = Field(description="Column name as it appears in the dataset")
    data_type: str = Field(description="Detected column type: numerical, categorical, or datetime")
    reason: str = Field(description="Analytical justification for selecting this column")
    is_target: bool = Field(default=False, description="True if identified as the primary target variable")


class InvestigationTask(BaseModel):
    """
    A single planned analytical investigation task.
    Does NOT contain statistical results (p-values, correlations, etc.) which belong to Phase 3.
    """
    task_id: str = Field(description="Unique task identifier, e.g. 'task_1' or 'T001'")
    task_type: TaskType = Field(description="Standardized analytical category")
    task: str = Field(description="Short human-readable task title")
    description: str = Field(description="Detailed description of what analysis should be conducted")
    method: str = Field(description="Recommended statistical/analytical method, e.g. 'Pearson correlation'")
    columns: list[str] = Field(description="List of columns involved in this task")
    column_a: Optional[str] = Field(default=None, description="First variable for bivariate/univariate analysis")
    column_b: Optional[str] = Field(default=None, description="Second variable for bivariate analysis")
    group_column: Optional[str] = Field(default=None, description="Grouping column for group comparison tasks")
    value_column: Optional[str] = Field(default=None, description="Numerical metric column for group comparison tasks")
    reason: str = Field(description="Statistical and analytical justification for this task")
    priority: PriorityLevel = Field(description="Task priority: 'high', 'medium', or 'low'")
    notes: Optional[list[str]] = Field(default=None, description="Data quality or methodology notes (e.g. outlier cautions)")


class PlannerRequest(BaseModel):
    """Input payload to request an investigation plan."""
    profile: Optional[dict[str, Any]] = Field(
        default=None,
        description="Phase 1 ProfileResponse dictionary"
    )
    dataset_id: Optional[str] = Field(
        default=None,
        description="Dataset identifier or uploaded filename for provenance"
    )
    objective: str = Field(
        default="Investigate this dataset.",
        description="Natural language analytical goal or question"
    )
    preferences: Optional[dict[str, Any]] = Field(
        default=None,
        description="Optional analysis preferences or constraints"
    )
    use_llm: Optional[bool] = Field(
        default=True,
        description="Explicitly enable/disable Gemini LLM planning. Defaults to True (genuine LLM planning enforced)."
    )


class PlannerResponse(BaseModel):
    """
    Structured output generated by the Planner Agent.
    Contains explicit analytical tasks ready for the future Phase 3 Analysis Agent
    and Phase 4 Critic Agent verification.
    """
    objective: str = Field(description="The user's original natural language objective")
    interpreted_goal: str = Field(description="Structured interpretation of the analytical objective")
    target_column: Optional[str] = Field(default=None, description="Identified primary target column if applicable")
    selected_columns: list[SelectedColumn] = Field(description="Columns selected for investigation with rationales")
    analysis_tasks: list[InvestigationTask] = Field(description="Ordered list of investigation tasks")
    tasks: list[InvestigationTask] = Field(description="Alias of analysis_tasks for flexible schema consumption")
    reasoning: list[str] = Field(description="Step-by-step reasoning behind the generated plan")
    warnings: list[str] = Field(description="Data quality warnings to consider during analysis")
    expected_outputs: list[str] = Field(description="Expected analytical deliverables from executing this plan")
    planner_mode: str = Field(default="deterministic", description="Mode used: 'deterministic' or 'llm'")
    planner_status: str = Field(default="success", description="Execution status: 'success' or 'failed'")
    planner_model: Optional[str] = Field(default=None, description="Actual model identifier used (e.g. 'gemini-3.5-flash-lite')")
    planner_provider: Optional[str] = Field(default=None, description="Provider used (e.g. 'google' or 'deterministic')")
    dataset_summary: Optional[dict[str, Any]] = Field(default=None, description="Key dataset dimensions summary")
